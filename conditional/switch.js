// switch
let day=5
switch (day) {
    case 1:
        console.log('monday');
        break;
    case 2:
        console.log('tuesday');
        break;
    case 3:
        console.log('wednsday');
        break;
    case 4:
        console.log('thursday');
        break;
    case 5:
        console.log('friday');
        break;
    case 6:
        console.log('saturday');
        break;

    default:
        console.log('sunday');
        break;
}


/*
note:
if you not write break and if case is match. it executed all cases after matching excepte default
*/